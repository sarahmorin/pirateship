from __future__ import annotations

from dataclasses import dataclass
import os
from typing import Any, Dict, List, Optional

from experiments import Experiment


@dataclass(frozen=True)
class NetworkBlip:
    """
    A time-bounded network impairment injected via iptables (keeps SSH alive).

    Notes:
    - Implemented as packet drop for the consensus TCP port range
      [node_port_base + 1, node_port_base + num_nodes].
    - Targets are *node names* (e.g. "node1") so the experiment can map them to VMs.
    """

    name: str
    start_s: int
    duration_s: int
    targets: List[str]  # node names

    # Future extension points (not implemented yet):
    # mode: str = "drop"  # drop|delay|loss...


class NetworkBlipExperiment(Experiment):
    """
    PirateShip experiment with an injected network blip during the run.

    This subclass only changes the generated arbiter script; protocol code is unchanged.
    """

    def __init__(
        self,
        name: str,
        group_name: str,
        seq_num: int,
        repeats: int,
        duration: int,
        num_nodes: int,
        num_clients: int,
        base_node_config: dict,
        base_client_config: dict,
        node_distribution: str,
        client_region: int,
        build_command: str,
        git_hash_override: Optional[str],
        project_home: str,
        controller_must_run: bool,
        network_blips: Optional[List[Dict[str, Any]]] = None,
    ):
        super().__init__(
            name,
            group_name,
            seq_num,
            repeats,
            duration,
            num_nodes,
            num_clients,
            base_node_config,
            base_client_config,
            node_distribution,
            client_region,
            build_command,
            git_hash_override,
            project_home,
            controller_must_run,
        )

        blips = network_blips or []
        parsed: List[NetworkBlip] = []
        for b in blips:
            parsed.append(
                NetworkBlip(
                    name=str(b["name"]),
                    start_s=int(b["start_s"]),
                    duration_s=int(b["duration_s"]),
                    targets=list(b["targets"]),
                )
            )
        self.network_blips: List[NetworkBlip] = parsed

        # Filled in after configs are generated:
        self._bin_to_vm = {}
        self._node_port_base = None

    def generate_configs(self, deployment, config_dir, log_dir):  # type: ignore[override]
        super().generate_configs(deployment, config_dir, log_dir)

        # Invert binary mapping so we can target a node by name during blips.
        bin_to_vm = {}
        for vm, bins in self.binary_mapping.items():
            for b in bins:
                bin_to_vm[b] = vm
        self._bin_to_vm = bin_to_vm
        self._node_port_base = int(deployment.node_port_base)

    def _vm_for_node(self, node_name: str):
        vm = self._bin_to_vm.get(node_name)
        if vm is None:
            raise ValueError(
                f"Network blip target {node_name!r} not found in experiment binary mapping"
            )
        return vm

    def generate_arbiter_script(self):  # type: ignore[override]
        # The arbiter script runs on the remote dev VM, so use remote paths
        remote_ssh_key = f"/users/{self.dev_ssh_user}/.ssh/id_ed25519"

        script_base = f"""#!/bin/bash
set -e
set -o xtrace

# This script is generated by the experiment pipeline. DO NOT EDIT.
SSH_CMD="ssh -o StrictHostKeyChecking=no -i {remote_ssh_key}"
SCP_CMD="scp -o StrictHostKeyChecking=no -i {remote_ssh_key}"

# Network blip is implemented via iptables on the *remote target VM* to drop
# only consensus traffic (keeps SSH alive on 22).
# NOTE: Assumes passwordless sudo on the target VMs.
PFT_BLIP_CHAIN="PFT_BLIP"
PFT_PORT_START={self._node_port_base + 1 if self._node_port_base is not None else 3001}
PFT_PORT_END={self._node_port_base + self.num_nodes if self._node_port_base is not None else 3000 + self.num_nodes}

"""
        chain = "PFT_BLIP"
        port_start = (
            self._node_port_base + 1
            if self._node_port_base is not None
            else 3001
        )
        port_end = (
            self._node_port_base + self.num_nodes
            if self._node_port_base is not None
            else 3000 + self.num_nodes
        )
        for repeat_num in range(self.repeats):
            _script = script_base[:]

            # Start binaries on each VM.
            for vm, bin_list in self.binary_mapping.items():
                for bin in bin_list:
                    if "node" in bin:
                        binary_name = "server"
                    elif "client" in bin:
                        binary_name = "client"
                    elif "controller" in bin:
                        binary_name = "controller"
                    else:
                        continue

                    _script += f"""
$SSH_CMD {self.dev_ssh_user}@{vm.public_ip} 'RUST_BACKTRACE=full {self.remote_workdir}/build/{binary_name} {self.remote_workdir}/configs/{bin}_config.json > {self.remote_workdir}/logs/{repeat_num}/{bin}.log 2> {self.remote_workdir}/logs/{repeat_num}/{bin}.err' &
PID="$PID $!"
"""

            # Schedule network blips (background) before the main sleep.
            for blip in self.network_blips:
                # Resolve targets to public IPs and log files.
                targets = []
                for node_name in blip.targets:
                    vm = self._vm_for_node(node_name)
                    log_path = f"{self.remote_workdir}/logs/{repeat_num}/{node_name}.log"
                    targets.append((node_name, vm.public_ip, log_path))

                # Build the background block.
                _script += f"""
(
  echo "Starting blip background process for {blip.name}"
  sleep {blip.start_s}
  echo "Blip {blip.name} starting at $(date)"
"""
                for (node_name, ip, log_path) in targets:
                    blip_log_path = log_path.replace('.log', '_blip.log')
                    blip_log_dir = os.path.dirname(blip_log_path)
                    _script += f"""
  echo "Creating blip log file: {blip_log_path}" || true
  $SSH_CMD {self.dev_ssh_user}@{ip} "mkdir -p {blip_log_dir}" || true
  $SSH_CMD {self.dev_ssh_user}@{ip} "touch {blip_log_path}" || true
  $SSH_CMD {self.dev_ssh_user}@{ip} "bash -lc 'ts=\\$(date -u +%Y-%m-%dT%H:%M:%S.%3N+00:00); echo \"[INFO][pft::experiment::blip][\\$ts] NETBLIP START name={blip.name}\" >> \"{blip_log_path}\"'" || true
  $SSH_CMD {self.dev_ssh_user}@{ip} "sudo -n iptables -N {chain} 2>/dev/null || true; sudo -n iptables -F {chain} || true; sudo -n iptables -C INPUT -j {chain} 2>/dev/null || sudo -n iptables -I INPUT -j {chain}; sudo -n iptables -C OUTPUT -j {chain} 2>/dev/null || sudo -n iptables -I OUTPUT -j {chain}; sudo -n iptables -A {chain} -p tcp --dport {port_start}:{port_end} -j DROP; sudo -n iptables -A {chain} -p tcp --sport {port_start}:{port_end} -j DROP" || true
  $SSH_CMD {self.dev_ssh_user}@{ip} "bash -lc 'echo \"[DEBUG] iptables rules:\" >> \"{blip_log_path}\"; sudo -n iptables -S {chain} >> \"{blip_log_path}\" 2>&1; sudo -n iptables -vnL {chain} >> \"{blip_log_path}\" 2>&1'" || true

  """

                _script += f"""
  sleep {blip.duration_s}
"""
                for (node_name, ip, log_path) in targets:
                    blip_log_path = log_path.replace('.log', '_blip.log')
                    _script += f"""
  $SSH_CMD {self.dev_ssh_user}@{ip} "sudo -n iptables -D INPUT -j {chain} 2>/dev/null || true; sudo -n iptables -D OUTPUT -j {chain} 2>/dev/null || true; sudo -n iptables -F {chain} 2>/dev/null || true; sudo -n iptables -X {chain} 2>/dev/null || true" || true
  $SSH_CMD {self.dev_ssh_user}@{ip} "bash -lc 'ts=\\$(date -u +%Y-%m-%dT%H:%M:%S.%3N+00:00); echo \"[INFO][pft::experiment::blip][\\$ts] NETBLIP END name={blip.name}\" >> \"{blip_log_path}\"'" || true
  $SSH_CMD {self.dev_ssh_user}@{ip} "ls -la {blip_log_path}" || true
"""

                _script += """
) &
"""

            _script += f"""
# Sleep for the duration of the experiment
sleep {self.duration}

# Kill the binaries. First with a SIGINT, then with a SIGTERM, then with a SIGKILL
echo -n $PID | xargs -d' ' -I{{}} kill -2 {{}} || true
echo -n $PID | xargs -d' ' -I{{}} kill -15 {{}} || true
echo -n $PID | xargs -d' ' -I{{}} kill -9 {{}} || true
sleep 10

# Kill the binaries in SSHed VMs as well. Calling SIGKILL on the local SSH process might have left them orphaned.
# Make sure not to kill the tmux server.
# Then copy the logs back and delete any db files. Cleanup for the next run.
"""

            for vm, bin_list in self.binary_mapping.items():
                for bin in bin_list:
                    if "node" in bin:
                        binary_name = "server"
                    elif "client" in bin:
                        binary_name = "client"
                    elif "controller" in bin:
                        binary_name = "controller"
                    else:
                        continue

                    _script += f"""
$SSH_CMD {self.dev_ssh_user}@{vm.public_ip} 'pkill -2 -c {binary_name}' || true
$SSH_CMD {self.dev_ssh_user}@{vm.public_ip} 'pkill -15 -c {binary_name}' || true
$SSH_CMD {self.dev_ssh_user}@{vm.public_ip} 'pkill -9 -c {binary_name}' || true
$SSH_CMD {self.dev_ssh_user}@{vm.public_ip} 'rm -rf /data/*' || true
$SCP_CMD {self.dev_ssh_user}@{vm.public_ip}:{self.remote_workdir}/logs/{repeat_num}/{bin}.log {self.remote_workdir}/logs/{repeat_num}/{bin}.log || true
$SCP_CMD {self.dev_ssh_user}@{vm.public_ip}:{self.remote_workdir}/logs/{repeat_num}/{bin}.err {self.remote_workdir}/logs/{repeat_num}/{bin}.err || true
$SCP_CMD {self.dev_ssh_user}@{vm.public_ip}:{self.remote_workdir}/logs/{repeat_num}/{bin}_blip.log {self.remote_workdir}/logs/{repeat_num}/{bin}_blip.log || true
"""

            _script += """
sleep 60
"""

            with open(os.path.join(self.local_workdir, f"arbiter_{repeat_num}.sh"), "w") as f:
                f.write(_script + "\n\n")


